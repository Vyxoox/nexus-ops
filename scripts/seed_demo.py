def seed(reset: bool = False) -> None:
    with app.app_context():
        db.create_all()

        if reset:
            LogAuditoria.query.delete()
            Funcionario.query.delete()
            Usuario.query.delete()
            db.session.commit()

        for login, senha, perfil, is_admin, is_superadmin, perms in USUARIOS_DEMO:
            user = Usuario.query.filter_by(login=login).first()
            if not user:
                user = Usuario(
                    login=login,
                    perfil=perfil,
                    is_admin=is_admin,
                    is_superadmin=is_superadmin,
                    permissoes=json.dumps(perms, ensure_ascii=False),
                )
                user.set_password(senha)
                db.session.add(user)
            else:
                user.perfil = perfil
                user.is_admin = is_admin
                user.is_superadmin = is_superadmin
                user.permissoes = json.dumps(perms, ensure_ascii=False)
                user.set_password(senha)

        db.session.commit()

        inseridos = 0
        for dados in COLABORADORES_DEMO:
            existente = Funcionario.query.filter_by(cpf=dados["cpf"]).first()
            if existente:
                continue
            db.session.add(Funcionario(**dados))
            inseridos += 1

        db.session.commit()

        if LogAuditoria.query.count() == 0:
            admin_user = Usuario.query.filter_by(login="admin").first()
            agora = datetime.now(UTC).replace(tzinfo=None)
            logs_iniciais = [
                LogAuditoria(
                    usuario_id=admin_user.id if admin_user else None,
                    usuario_login="admin",
                    acao="AUTH_LOGIN_SUCESSO",
                    categoria="seguranca",
                    status="sucesso",
                    recurso="usuario",
                    recurso_id=str(admin_user.id) if admin_user else "1",
                    metodo_http="POST",
                    rota="/login",
                    ip_origem="127.0.0.1",
                    detalhes=json.dumps({"login_informado": "admin"}),
                    criado_em=agora - timedelta(hours=3),
                ),
                LogAuditoria(
                    usuario_id=admin_user.id if admin_user else None,
                    usuario_login="admin",
                    acao="REINDEXAR_TODOS_SUCESSO",
                    categoria="indexacao",
                    status="sucesso",
                    recurso="funcionarios",
                    metodo_http="POST",
                    rota="/reindexar",
                    ip_origem="127.0.0.1",
                    detalhes=json.dumps({"total_ativos": 18}),
                    criado_em=agora - timedelta(hours=2),
                ),
                LogAuditoria(
                    usuario_id=None,
                    usuario_login=None,
                    acao="AUTH_LOGIN_FALHA",
                    categoria="seguranca",
                    status="falha",
                    recurso="usuario",
                    metodo_http="POST",
                    rota="/login",
                    ip_origem="198.51.100.42",
                    detalhes=json.dumps({"login_informado": "usuario.teste"}),
                    criado_em=agora - timedelta(minutes=45),
                ),
            ]
            db.session.add_all(logs_iniciais)
            db.session.commit()

        reindexar_todos()
        total_funcs = Funcionario.query.count()
        total_users = Usuario.query.count()
        print(f"Seed concluído: {total_users} usuários, {total_funcs} colaboradores ({inseridos} novos) e índice Whoosh atualizado.")


def main() -> int:
    parser = argparse.ArgumentParser(description="Popula dados fictícios de demonstração para o Nexus People & Ops.")
    parser.add_argument("--reset", action="store_true", help="Limpa tabelas antes de inserir os dados de demonstração.")
    args = parser.parse_args()
    seed(reset=args.reset)
    return 0


